#!/usr/bin/env node
// ============================================================================
// sync-edge-workforce-engine.mjs
// ----------------------------------------------------------------------------
// DEBT-074 (Stage 2): the scheduled monthly auto-create runs as a Supabase
// Edge Function (Deno), which cannot import the `@line-os/workforce` monorepo
// package. To keep exactly ONE implementation of the scheduling engine, this
// script copies the engine's two source files verbatim into
// `supabase/functions/_shared/workforce-engine/`, only rewriting relative
// `.js` import specifiers to `.ts` (Deno resolves real file names) and
// prepending a "GENERATED -- do not edit" header.
//
// Usage (after any change to packages/workforce/src/auto-distribute.ts or
// auto-distribution-authority.ts):
//
//   node scripts/sync-edge-workforce-engine.mjs
//
// Drift guard: `supabase/functions/_shared/workforce-engine/engine-sync.test.ts`
// (run by `pnpm --filter @line-os/config test`) asserts the committed copies
// equal `transformEngineSource(...)` of the current sources, so CI fails if
// the engine changes without a re-sync.
// ============================================================================

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export const ENGINE_FILES = ['auto-distribute.ts', 'auto-distribution-authority.ts'];
export const ENGINE_SOURCE_DIR = join(REPO_ROOT, 'packages', 'workforce', 'src');
export const ENGINE_TARGET_DIR = join(REPO_ROOT, 'supabase', 'functions', '_shared', 'workforce-engine');

/** First line of every generated copy (followed by the source file name). */
export const GENERATED_HEADER_PREFIX =
  '// GENERATED by scripts/sync-edge-workforce-engine.mjs — do not edit. Source: packages/workforce/src/';

/**
 * Pure transform: normalizes line endings to LF, rewrites relative `.js`
 * import/export specifiers to `.ts`, and prepends the generated header.
 */
export function transformEngineSource(fileName, source) {
  const normalized = source.replace(/\r\n/g, '\n');
  const rewritten = normalized.replace(/(\bfrom\s+['"])(\.{1,2}\/[^'"]+?)\.js(['"])/g, '$1$2.ts$3');
  return `${GENERATED_HEADER_PREFIX}${fileName}\n${rewritten}`;
}

function main() {
  mkdirSync(ENGINE_TARGET_DIR, { recursive: true });
  for (const fileName of ENGINE_FILES) {
    const source = readFileSync(join(ENGINE_SOURCE_DIR, fileName), 'utf8');
    writeFileSync(join(ENGINE_TARGET_DIR, fileName), transformEngineSource(fileName, source), 'utf8');
    console.log(`synced ${fileName}`);
  }
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  main();
}
