#!/usr/bin/env node
// ============================================================================
// sync-edge-provisioning.mjs
// ----------------------------------------------------------------------------
// Stage 4B-2: the provision-tenant Edge Function (Deno) validates its input
// and builds the core.provision_tenant payload with the SAME pure code as
// packages/db (input rules, Cafe package template v3, HACCP manifest, payload
// builder + validator). Deno cannot import the pnpm workspace, so -- like
// scripts/sync-edge-workforce-engine.mjs -- this script copies those source
// files verbatim into `supabase/functions/_shared/provisioning/`, only
// rewriting relative `.js` import specifiers to `.ts` and prepending a
// "GENERATED -- do not edit" header. ONE implementation, two runtimes.
//
// Usage (after any change to one of PROVISIONING_FILES in packages/db/scripts):
//
//   node scripts/sync-edge-provisioning.mjs
//
// Drift guard: `supabase/functions/_shared/provisioning/provisioning-sync.test.ts`
// (run by `pnpm --filter @line-os/config test`).
// ============================================================================

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

export const PROVISIONING_FILES = [
  'tenant-input-rules.ts',
  'cafe-haccp-presets.ts',
  'cafe-package-template.ts',
  'provisioning-payload.ts',
];
export const PROVISIONING_SOURCE_DIR = join(REPO_ROOT, 'packages', 'db', 'scripts');
export const PROVISIONING_TARGET_DIR = join(REPO_ROOT, 'supabase', 'functions', '_shared', 'provisioning');

/** First line of every generated copy (followed by the source file name). */
export const PROVISIONING_HEADER_PREFIX =
  '// GENERATED by scripts/sync-edge-provisioning.mjs — do not edit. Source: packages/db/scripts/';

/** Pure transform: LF line endings, relative `.js` specifiers -> `.ts`, generated header. */
export function transformProvisioningSource(fileName, source) {
  const normalized = source.replace(/\r\n/g, '\n');
  const rewritten = normalized.replace(/(\bfrom\s+['"])(\.{1,2}\/[^'"]+?)\.js(['"])/g, '$1$2.ts$3');
  return `${PROVISIONING_HEADER_PREFIX}${fileName}\n${rewritten}`;
}

function main() {
  mkdirSync(PROVISIONING_TARGET_DIR, { recursive: true });
  for (const fileName of PROVISIONING_FILES) {
    const source = readFileSync(join(PROVISIONING_SOURCE_DIR, fileName), 'utf8');
    writeFileSync(join(PROVISIONING_TARGET_DIR, fileName), transformProvisioningSource(fileName, source), 'utf8');
    console.log(`synced ${fileName}`);
  }
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  main();
}
